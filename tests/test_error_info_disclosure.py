def test_sanitize_inbound_passes_safe_values() -> None:
    assert _sanitize_inbound("req_abc123") == "req_abc123"
    assert _sanitize_inbound("a-b_c.d/e:f+g") == "a-b_c.d/e:f+g"


def test_sanitize_inbound_replaces_unsafe_chars() -> None:
    assert _sanitize_inbound("hello world\nfoo") == "hello_world_foo"
    assert _sanitize_inbound("<script>") == "_script_"


def test_sanitize_inbound_truncates_long_values() -> None:
    long = "a" * 5_000
    out = _sanitize_inbound(long)
    assert out is not None
    assert len(out) == 128


def test_sanitize_inbound_returns_none_for_empty() -> None:
    assert _sanitize_inbound("") is None
    # Whitespace is replaced with underscores (not dropped), so the
    # result is a non-empty string of underscores.
    assert _sanitize_inbound("   ") == "___"
    # Control characters are replaced with underscores, so the result
    # is a non-empty string of underscores (not None). The test for
    # "rejects CRLF injection" below verifies the security-relevant
    # property (no CR/LF surviving the cleaner).
    assert _sanitize_inbound("\x00\x01") == "__"


def test_sanitize_inbound_rejects_crlf_injection() -> None:
    """The sanitizer must not allow CRLF injection in the response header."""

    out = _sanitize_inbound("req_abc\r\nSet-Cookie: pwn=1")
    assert out is not None
    assert "\r" not in out
    assert "\n" not in out


