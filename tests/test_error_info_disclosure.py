"""Tests for the error-info-disclosure hardening (issue #79).

The fix has three parts:

1. A request-id middleware that attaches (or reuses) an ``X-Request-ID``
   header on every response, including 500s generated by Starlette's
   outermost ``ServerErrorMiddleware``.
2. A global ``Exception`` handler that returns a sanitized 500 with
   the generic message + request id, never the raw exception text.
3. Replaced ``detail=str(e)`` callsites in
   ``orchestrator/main.py`` (chat completion) and the cookie policy
   paths in ``orchestrator/routes/auth_setup.py`` with stable error
   codes and server-side logging.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

import pytest
from fastapi import FastAPI
from httpx import ASGITransport, AsyncClient

from orchestrator.main import (
    REQUEST_ID_HEADER,
    _GENERIC_INTERNAL_ERROR,
    _generic_exception_handler,
    app,
)
from orchestrator.request_id import (
    REQUEST_ID_HEADER as REQUEST_ID_HEADER_CONST,
    RequestIdMiddleware,
    _OuterRequestIdMiddleware,
    _sanitize_inbound,
)


ROOT = Path(__file__).resolve().parents[1]


def _build_crash_app_with_handler() -> FastAPI:
    """Build a tiny FastAPI app with the production global exception handler
    and the outer request-id middleware wrap, so 500 responses generated
    by Starlette's outermost ServerErrorMiddleware carry both the
    sanitized body and the request id."""

    crash_app = FastAPI()
    crash_app.add_exception_handler(Exception, _generic_exception_handler)
    _built = crash_app.build_middleware_stack()
    crash_app.middleware_stack = _OuterRequestIdMiddleware(_built)
    return crash_app


