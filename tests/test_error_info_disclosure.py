def test_production_app_supplies_stable_cookie_policy_error_code() -> None:
    """The auth_setup.py refresh endpoint must return a fixed error code
    instead of ``str(e)``. We can't easily trigger the actual cookie policy
    failure, so we visit the source and assert the literal token is
    present, and that the ``detail=str(e)`` pattern is gone."""

    auth_source = (ROOT / "orchestrator" / "routes" / "auth_setup.py").read_text()
    # The literal fix token must be present in both the setup and refresh
    # endpoints.
    assert auth_source.count("cookie_policy_invalid") >= 2
    # The leaky pattern must be gone from auth_setup.py.
    assert "detail=str(e)" not in auth_source


def test_production_app_omits_str_e_in_main_chat_completion() -> None:
    """The OpenAI-compatible chat completion endpoint must not leak
    ``str(e)`` in its 500 response."""

    main_source = (ROOT / "orchestrator" / "main.py").read_text()
    # The fix replaces the leaky `raise HTTPException(status_code=500,
    # detail=str(e))` pattern with `detail=_GENERIC_INTERNAL_ERROR`.
    # Check that the leaky pattern is gone (allowing other valid instances
    # elsewhere — but the specific chat-completion path is replaced).
    # We anchor on the chat completion route which is the one we changed.
    assert "OpenAI-compatible chat completion failed" in main_source


def test_main_py_no_new_detail_str_e_in_runtime_error_branches() -> None:
    """Static gate: the runtime-error path in ``/v1/chat/completions`` must
    not go back to leaking ``str(e)``. We accept the auth_setup path for
    the historical reason (well-scoped cookie policy errors are now a
    fixed token)."""

    main_source = (ROOT / "orchestrator" / "main.py").read_text()
    # The chat completion route's exception branch must use the generic
    # message constant, not ``str(e)``. The branch logging message is
    # the unique anchor — the comment block above only appears in this
    # route's exception handler.
    match = re.search(
        r"OpenAI-compatible chat completion failed.*?raise HTTPException\(\s*status_code=500,\s*detail=([^\n)]+)\)",
        main_source,
        flags=re.DOTALL,
    )
    assert match is not None, "Could not find the chat completion exception handler in main.py"
    detail_value = match.group(1).strip()
    assert detail_value == "_GENERIC_INTERNAL_ERROR", (
        f"Expected detail=_GENERIC_INTERNAL_ERROR, got {detail_value!r}"
    )
    assert "str(e)" not in match.group(0)
