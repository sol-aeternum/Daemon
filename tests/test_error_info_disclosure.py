@pytest.mark.asyncio
async def test_unhandled_exception_returns_generic_message_no_leak() -> None:
    """Issue #79: unhandled exceptions must not leak Python exception text,
    file paths, or function names in the response body."""

    crash_app = _build_crash_app_with_handler()

    @crash_app.get("/boom")
    async def boom() -> None:
        # Use a very specific exception message that includes a recognizable
        # fingerprint so the assertion can detect any leak.
        raise RuntimeError("fingerprint-leak-7e3a9b: /orchestrator/secret_path.py leaked fn name")

    async with AsyncClient(
        transport=ASGITransport(app=crash_app, raise_app_exceptions=False),
        base_url="http://test",
    ) as client:
        response = await client.get("/boom")

    assert response.status_code == 500
    body = response.text
    assert "fingerprint-leak-7e3a9b" not in body
    assert "/secret_path.py" not in body
    assert "RuntimeError" not in body
    assert _GENERIC_INTERNAL_ERROR in body


@pytest.mark.asyncio
async def test_unhandled_exception_includes_request_id_in_body() -> None:
    """The request id is the correlation handle for support — it must be
    present in the response body for the operator fetch logs."""

    crash_app = _build_crash_app_with_handler()

    @crash_app.get("/boom")
    async def boom() -> None:
        raise RuntimeError("oh no")

    async with AsyncClient(
        transport=ASGITransport(app=crash_app, raise_app_exceptions=False),
        base_url="http://test",
    ) as client:
        response = await client.get("/boom", headers={REQUEST_ID_HEADER: "req_correlation_xyz"})

    assert response.status_code == 500
    body = response.json()
    assert body["request_id"] == "req_correlation_xyz"
    assert body["detail"] == _GENERIC_INTERNAL_ERROR


