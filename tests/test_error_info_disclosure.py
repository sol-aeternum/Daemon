ROOT = Path(__file__).resolve().parents[1]


def _build_crash_app_with_handler() -> FastAPI:
    """Build a tiny FastAPI app with the production global exception handler
    and the outer request-id middleware wrap, so 500 responses generated
    by Starlette's outermost ServerErrorMiddleware carry both the
    sanitized body and the request id."""

    crash_app = FastAPI()
    crash_app.add_exception_handler(Exception, _generic_exception_handler)
    _built = crash_app.build_middleware_stack()
    crash_app.middleware_stack = _OuterRequestIdMiddleware(_built)
    return crash_app


